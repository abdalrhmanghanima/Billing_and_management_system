/* --------------------------------------------------------------------------
   Toast / Snackbar Notification Manager
   CRITICAL REQUIREMENT: Positioned at top with z-index 99999 so it is
   ABOVE bottom sheets and bottom navigation.
   -------------------------------------------------------------------------- */
const ToastManager = {
  show(message, type = 'success', duration = 3200) {
    let container = document.getElementById('app-snackbar-container');
    if (!container) {
      container = document.createElement('div');
      container.id = 'app-snackbar-container';
      container.className = 'app-snackbar-container';
      document.body.appendChild(container);
    }

    const toast = document.createElement('div');
    toast.className = `app-snackbar ${type}`;

    const iconSvg = type === 'success' ? Icons.check() : Icons.alertCircle();

    toast.innerHTML = `
      <div class="snackbar-content">
        ${iconSvg}
        <span>${message}</span>
      </div>
      <button class="snackbar-close-btn" aria-label="Close">
        ${Icons.close()}
      </button>
    `;

    toast.querySelector('.snackbar-close-btn').addEventListener('click', () => {
      toast.remove();
    });

    container.appendChild(toast);

    setTimeout(() => {
      toast.style.opacity = '0';
      toast.style.transform = 'translateY(-10px)';
      toast.style.transition = 'all 0.3s ease';
      setTimeout(() => toast.remove(), 300);
    }, duration);
  }
};

/* --------------------------------------------------------------------------
   Mobile Bottom Sheet Manager
   -------------------------------------------------------------------------- */
const BottomSheetManager = {
  open({ title, contentHtml, onRender }) {
    const backdrop = document.getElementById('app-bottom-sheet-backdrop');
    const headerTitle = document.getElementById('app-bottom-sheet-title');
    const body = document.getElementById('app-bottom-sheet-body');

    if (!backdrop || !headerTitle || !body) return;

    headerTitle.textContent = title || '';
    body.innerHTML = contentHtml;

    backdrop.classList.add('active');

    if (typeof onRender === 'function') {
      onRender(body);
    }
  },

  close() {
    const backdrop = document.getElementById('app-bottom-sheet-backdrop');
    if (backdrop) {
      backdrop.classList.remove('active');
    }
  }
};

/* --------------------------------------------------------------------------
   UI Helpers & Renderers
   -------------------------------------------------------------------------- */
const UI = {
  // Render empty state card
  createEmptyState({ icon, title, desc, actionText, actionId }) {
    return `
      <div class="empty-state-card">
        <div class="empty-state-icon-box">
          ${icon || Icons.search()}
        </div>
        <h4 class="empty-state-title">${title || 'No data found'}</h4>
        <p class="empty-state-desc">${desc || 'There are no items to display right now.'}</p>
        ${actionText ? `<button class="btn btn-primary btn-sm" id="${actionId}">${actionText}</button>` : ''}
      </div>
    `;
  },

  // Render skeleton loading list
  createSkeletonList(count = 5) {
    let html = '<div class="skeleton-list">';
    for (let i = 0; i < count; i++) {
      html += `
        <div class="skeleton skeleton-card" style="margin-bottom: 12px; display: flex; align-items: center; padding: 12px; gap: 12px;">
          <div class="skeleton" style="width: 44px; height: 44px; border-radius: 10px;"></div>
          <div style="flex: 1;">
            <div class="skeleton" style="width: 50%; height: 16px; margin-bottom: 6px;"></div>
            <div class="skeleton" style="width: 75%; height: 12px;"></div>
          </div>
        </div>
      `;
    }
    html += '</div>';
    return html;
  },

  // Clear validation errors on inputs
  clearFieldErrors(container) {
    container.querySelectorAll('.has-error').forEach(el => el.classList.remove('has-error'));
    container.querySelectorAll('.field-error-hint').forEach(el => el.remove());
  },

  // Display validation error under specific input
  showFieldError(inputElement, errorMessage) {
    if (!inputElement) return;
    inputElement.classList.add('has-error');

    // Remove existing hint if any
    const parent = inputElement.closest('.form-group') || inputElement.parentElement;
    const existing = parent.querySelector('.field-error-hint');
    if (existing) existing.remove();

    const hint = document.createElement('div');
    hint.className = 'field-error-hint';
    hint.innerHTML = `${Icons.alertCircle()}<span>${errorMessage}</span>`;
    parent.appendChild(hint);
  }
};

window.Icons = Icons;
window.ToastManager = ToastManager;
window.BottomSheetManager = BottomSheetManager;
window.UI = UI;
