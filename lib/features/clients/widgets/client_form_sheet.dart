import 'package:billing_and_sales_management/core/enums/save_result.dart';
import 'package:billing_and_sales_management/core/translate/app_translate.dart';
import 'package:billing_and_sales_management/domain/clients/entities/client.dart';
import 'package:billing_and_sales_management/features/clients/providers/clients_notifier.dart';
import 'package:billing_and_sales_management/responsive/responsive.dart';
import 'package:easy_localization/easy_localization.dart';
import 'package:flutter/material.dart';
import 'package:flutter_riverpod/flutter_riverpod.dart';

class ClientFormSheet extends ConsumerStatefulWidget {
  const ClientFormSheet({super.key, this.existing});

  final Client? existing;

  @override
  ConsumerState<ClientFormSheet> createState() => _ClientFormSheetState();
}

class _ClientFormSheetState extends ConsumerState<ClientFormSheet> {
  late final TextEditingController _nameController;
  late final TextEditingController _phoneController;
  late final TextEditingController _addressController;

  String? _nameError;
  String? _phoneError;
  String? _addressError;
  bool _isSaving = false;

  bool get _isEditing => widget.existing != null;

  static final RegExp _phoneRegex = RegExp(r'^[0-9]{11}$');

  @override
  void initState() {
    super.initState();
    _nameController = TextEditingController(text: widget.existing?.name ?? '');
    _phoneController = TextEditingController(
      text: widget.existing?.phone ?? '',
    );
    _addressController = TextEditingController(
      text: widget.existing?.address ?? '',
    );
    if (!_isEditing) {
      WidgetsBinding.instance.addPostFrameCallback((_) {
        if (!mounted) return;
        ref.invalidate(nextClientNumberProvider);
      });
    }
  }

  @override
  void dispose() {
    _nameController.dispose();
    _phoneController.dispose();
    _addressController.dispose();
    super.dispose();
  }

  Future<void> _save() async {
    if (_isSaving) return;

    final name = _nameController.text.trim();
    final phone = _phoneController.text.trim();
    final address = _addressController.text.trim();

    final nameInvalid = name.isEmpty;
    final phoneEmpty = phone.isEmpty;
    final phoneInvalid = !phoneEmpty && !_phoneRegex.hasMatch(phone);
    final addressInvalid = address.isEmpty;

    setState(() {
      _nameError = nameInvalid ? AppTranslate.clientNameRequired.tr() : null;
      _phoneError = phoneEmpty
          ? AppTranslate.phoneRequired.tr()
          : phoneInvalid
          ? AppTranslate.phoneInvalid.tr()
          : null;
      _addressError = addressInvalid ? AppTranslate.addressRequired.tr() : null;
    });

    if (nameInvalid || phoneEmpty || phoneInvalid || addressInvalid) return;

    setState(() => _isSaving = true);

    final notifier = ref.read(clientsProvider.notifier);
    final result = _isEditing
        ? await notifier.updateClient(
            id: widget.existing!.id,
            number: widget.existing!.number,
            name: name,
            phone: phone,
            address: address,
          )
        : await notifier.addClient(name: name, phone: phone, address: address);

    if (!mounted) return;

    setState(() => _isSaving = false);

    switch (result) {
      case SaveResult.success:
        CustomSnackbar.showSuccess(
          context,
          _isEditing
              ? AppTranslate.clientUpdatedSuccessfully.tr()
              : AppTranslate.clientAddedSuccessfully.tr(
                  namedArgs: {'name': name},
                ),
        );
        Navigator.of(context).pop();
      case SaveResult.duplicate:
        setState(() => _nameError = AppTranslate.clientNameAlreadyExists.tr());
      case SaveResult.failure:
        CustomSnackbar.showError(
          context,
          _isEditing
              ? AppTranslate.couldNotUpdateClient.tr()
              : AppTranslate.couldNotSaveClient.tr(),
        );
    }
  }

  @override
  Widget build(BuildContext context) {
    final nextNumberText = _isEditing
        ? '#${widget.existing!.number}'
        : ref
              .watch(nextClientNumberProvider)
              .maybeWhen(
                data: (number) => '#$number',
                error: (_, _) => AppTranslate.autoGenerated.tr(),
                orElse: () => AppTranslate.generating.tr(),
              );

    return SingleChildScrollView(
      child: Column(
        mainAxisSize: MainAxisSize.min,
        crossAxisAlignment: CrossAxisAlignment.stretch,
        children: [
          CustomTextField(
            controller: _nameController,
            label: AppTranslate.clientName.tr(),
            isRequired: true,
            hint: AppTranslate.enterClientName.tr(),
            errorText: _nameError,
            enabled: !_isSaving,
            textInputAction: TextInputAction.next,
            onChanged: (_) {
              if (_nameError != null) setState(() => _nameError = null);
            },
          ),
          SizedBox(height: AppSpacing.formGroupGap.h),
          CustomTextField(
            controller: _phoneController,
            label: AppTranslate.phoneNumber11Digits.tr(),
            isRequired: true,
            hint: '01123456789',
            errorText: _phoneError,
            enabled: !_isSaving,
            keyboardType: TextInputType.phone,
            textInputAction: TextInputAction.next,
            onChanged: (_) {
              if (_phoneError != null) setState(() => _phoneError = null);
            },
          ),
          SizedBox(height: AppSpacing.formGroupGap.h),
          CustomTextField(
            key: ValueKey<String>(nextNumberText),
            initialValue: nextNumberText,
            label: AppTranslate.clientNumberAuto.tr(),
            enabled: false,
          ),
          SizedBox(height: AppSpacing.formGroupGap.h),
          CustomTextField(
            controller: _addressController,
            label: AppTranslate.address.tr(),
            isRequired: true,
            hint: AppTranslate.enterAddress.tr(),
            errorText: _addressError,
            enabled: !_isSaving,
            textInputAction: TextInputAction.done,
            onChanged: (_) {
              if (_addressError != null) setState(() => _addressError = null);
            },
          ),
          SizedBox(height: AppSpacing.lg.h),
          CustomButton(
            text: _isEditing
                ? AppTranslate.updateClient.tr()
                : AppTranslate.saveClient.tr(),
            onPressed: _save,
            loading: _isSaving,
          ),
        ],
      ),
    );
  }
}
